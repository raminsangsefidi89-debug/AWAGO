#!/usr/bin/env python3
"""Verify market/news data sources BY CALLING THEM, writing docs/DATA_SOURCES.md.

Run on a machine with internet access:
    python scripts/verify_sources.py --out docs/DATA_SOURCES.md

In the build sandbox (network restricted) the script runs but every probe
reports "unreachable", which is itself the honest recorded status.

Rows: name | URL | auth | rate limits | history depth | update frequency |
terms | status | last verified. Nothing is upgraded to "verified" unless the
probe actually succeeded — verified_live is never assumed.
"""

from __future__ import annotations

import argparse
import datetime as dt
from pathlib import Path

import httpx

from app.services.markets.providers import ALL_SOURCES, MarketSource

HEADER = """# AWAGO Data Sources

_Last verified: {when} — generated by `scripts/verify_sources.py`._

> Policy: sources are verified **by actually calling them**. Status
> `unverified` means the build environment could not reach the host; it does
> NOT mean the source works. Sources that forbid scraping are never scraped —
> use the CSV/Excel import or manual entry paths instead. Iran-market quotes
> are always displayed as **unofficial market quotes**.

| # | Source | URL | Auth | Rate limits | History depth | Update | Terms | Status | Verified live | Checked |
|---|--------|-----|------|-------------|---------------|--------|-------|--------|---------------|---------|
"""


def verify_one(src: MarketSource, client: httpx.Client) -> list[str]:
    rec = src.probe(client)
    return [
        str(rec.get("id", "")),
        str(rec.get("url", "")),
        str(rec.get("auth", "")),
        str(rec.get("rate_limit", "")),
        str(rec.get("history", "")),
        str(rec.get("update_frequency", "")),
        str(rec.get("terms", "")),
        str(rec.get("status", "")),
        "yes" if rec.get("verified_live") else "no",
        str(rec.get("last_checked") or dt.datetime.now(dt.timezone.utc).isoformat()),
    ]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default="docs/DATA_SOURCES.md")
    args = ap.parse_args()

    lines = [HEADER.format(when=dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"))]
    with httpx.Client() as client:
        for i, src in enumerate(ALL_SOURCES, 1):
            row = verify_one(src, client)
            lines.append(f"| {i} | " + " | ".join(row) + " |\n")

    lines.append(
        "\n## Import fallback\n\n"
        "Where no legitimate API exists, use `awago` CSV/Excel import "
        "(`data/imports/`) or the manual-entry endpoint; the app labels such "
        "data `imported`/`manual` with its provenance and never presents it "
        "as a live feed.\n"
    )
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("".join(lines), encoding="utf-8")
    print(f"wrote {out} ({len(ALL_SOURCES)} sources probed)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
