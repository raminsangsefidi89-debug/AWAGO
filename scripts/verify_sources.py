#!/usr/bin/env python3
"""Verify market/news data sources BY CALLING THEM, writing rows to docs/DATA_SOURCES.md.

Run on a machine with internet access:
    PYTHONPATH=. python scripts/verify_sources.py --out docs/DATA_SOURCES.md

The script APPENDS a dated section; earlier sections are preserved. In the
build sandbox (network restricted) every probe reports "unreachable", which
is itself the honest recorded status. Nothing becomes "verified" unless the
probe actually succeeded.

Rows: name | URL | auth | rate limits | history depth | update frequency |
terms | status | last verified.
"""

from __future__ import annotations

import argparse
import datetime as dt
from pathlib import Path

import httpx

from app.services.markets.providers import ALL_SOURCES, MarketSource
from app.services.news.fetcher import FEEDS

SECTION_HEADER = """
## Market & news sources (addendum) — verified by probing

_Verified: {when} — generated by `scripts/verify_sources.py`._

> Policy: sources are verified **by actually calling them**. Status
> `unreachable` / `unverified` means the probing machine could not reach the
> host — it does NOT mean the source works. Sources that forbid scraping are
> never scraped: use the CSV/Excel import or manual-entry paths instead.
> Iran-market quotes are always displayed as **unofficial market quotes**.

### Market data

| # | Source | URL | Auth | Rate limits | History depth | Update | Terms | Status | Verified live | Checked |
|---|--------|-----|------|-------------|---------------|--------|-------|--------|---------------|---------|
"""


def _probe_market(src: MarketSource, client: httpx.Client) -> list[str]:
    rec = src.probe(client)
    return [
        str(rec.get("id", "")),
        str(rec.get("url", "")),
        str(rec.get("auth", "")),
        str(rec.get("rate_limit", "")),
        str(rec.get("history", "")),
        str(rec.get("update_frequency", "")),
        str(rec.get("terms", "")),
        str(rec.get("status", "")),
        "yes" if rec.get("verified_live") else "no",
        str(rec.get("last_checked") or dt.datetime.now(dt.timezone.utc).isoformat()),
    ]


def _probe_feed(feed, client: httpx.Client) -> list[str]:
    now = dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds")
    try:
        r = client.head(feed.url, timeout=15)
        if r.status_code >= 400:
            r = client.get(feed.url, timeout=15)
        ok = r.status_code < 400
        status = f"reachable (HTTP {r.status_code})"
    except Exception as exc:
        ok = False
        status = f"unreachable: {exc}"[:120]
    return [
        feed.id,
        feed.url,
        "none",
        "verify; poll >= 15 min",
        "headline metadata only",
        "event-driven",
        feed.notes or "check ToS/robots",
        status,
        "yes" if ok else "no",
        now,
    ]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default="docs/DATA_SOURCES.md")
    args = ap.parse_args()

    when = dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds")
    lines = [SECTION_HEADER.format(when=when)]
    with httpx.Client(follow_redirects=True) as client:
        for i, src in enumerate(ALL_SOURCES, 1):
            lines.append(f"| {i} | " + " | ".join(_probe_market(src, client)) + " |\n")
        lines.append(
            "\n### News feeds\n\n| # | Feed | URL | Auth | Rate limits | History | Update | Terms | Status | Verified live | Checked |\n|---|------|-----|------|-------------|---------|--------|-------|--------|---------------|---------|\n"
        )
        for i, feed in enumerate(FEEDS, 1):
            lines.append(f"| {i} | " + " | ".join(_probe_feed(feed, client)) + " |\n")

    lines.append(
        "\n### Import fallback\n\n"
        "Where no legitimate API exists, use the CSV/Excel import "
        "(`data/imports/`) or the manual-entry path; the app labels such data "
        "`imported`/`manual` with its provenance and never presents it as a "
        "live feed.\n"
    )
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    prev = out.read_text(encoding="utf-8") if out.exists() else ""
    out.write_text(prev + "".join(lines), encoding="utf-8")
    print(f"appended to {out} ({len(ALL_SOURCES)} market sources, {len(FEEDS)} news feeds probed)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
